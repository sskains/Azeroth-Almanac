"""Builds AzerothAlmanac/Data/CreatureVoices.lua: the sound a creature's Wild Gambit card makes when it's
played (Shannon, 2026-10-11; DESIGN 96).

Inputs:
  1. a JSON pack of the game's Classic Era sound tables from wago.tools (CreatureDisplayInfo,
     CreatureModelData, CreatureSoundData, NPCSounds), as saved by the Chrome fetch of 2026-10-11
     (almanac_voice_tables.json: { "tables": { name: csv text } });
  2. the VMaNGOS world database (SQLite) for each creature's models.

For every model (display ID): its NPC greeting sound kit (spoken words, for the races' townsfolk,
guards and enemies), its battle cry (CreatureSoundData.SoundAggroID) and its attack grunt
(SoundExertionID). Each distinct trio is written once (SETS); models and creatures point at it.

  python3 tools/build_voices.py <almanac_voice_tables.json> <mangos.sqlite>
"""
import csv, io, json, os, sqlite3, sys
from datetime import date

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "AzerothAlmanac"))


def rows(text):
    return list(csv.DictReader(io.StringIO(text)))


def main(pack_path, db_path):
    t = json.load(open(pack_path, encoding="utf-8"))["tables"]
    model_sound = {r["ID"]: r["SoundID"] for r in rows(t["CreatureModelData"])}
    sound = {r["ID"]: r for r in rows(t["CreatureSoundData"])}
    npc_sound = {r["ID"]: r for r in rows(t["NPCSounds"])}
    by_display = {}
    for r in rows(t["CreatureDisplayInfo"]):
        sid = r["SoundID"] if r["SoundID"] not in ("", "0") else model_sound.get(r["ModelID"])
        s = sound.get(sid) or {}
        n = npc_sound.get(r["NPCSoundID"]) or {}
        trio = (int(n.get("SoundID_0") or 0), int(s.get("SoundAggroID") or 0), int(s.get("SoundExertionID") or 0))
        if any(trio):
            by_display[int(r["ID"])] = trio

    db = sqlite3.connect(db_path)
    by_npc = {}
    for entry, *ds in db.execute("select entry, display_id1, display_id2, display_id3, display_id4 from creature_template"):
        best = None
        for d in ds:
            trio = d and by_display.get(d)
            if trio and (best is None or (trio[0] and not best[0]) or (trio[1] and not best[1] and not best[0])):
                best = trio
        if best:
            by_npc[entry] = best

    # only the models creatures use (cards know their display), and every creature
    used = set()
    for row in db.execute("select display_id1, display_id2, display_id3, display_id4 from creature_template"):
        used.update(d for d in row if d)
    displays = {d: v for d, v in by_display.items() if d in used}
    sets, index = [], {}
    def idx(trio):
        if trio not in index:
            index[trio] = len(sets) + 1
            sets.append(trio)
        return index[trio]
    disp_idx = {d: idx(v) for d, v in sorted(displays.items())}
    npc_idx = {n: idx(v) for n, v in sorted(by_npc.items())}

    out = [
        "-- Generated by tools/build_voices.py on %s from the game's Classic Era sound tables (wago.tools:" % date.today().isoformat(),
        "-- CreatureDisplayInfo, CreatureModelData, CreatureSoundData, NPCSounds) and the VMaNGOS world database",
        "-- (github.com/vmangos/core, GPL-2.0; see Licenses\\VMaNGOS.txt). Do not edit by hand.",
        "-- SETS[i] = { greeting sound kit (spoken words), battle cry kit, attack grunt kit } (0 = none);",
        "-- DISPLAY[displayID] and NPC[creatureID] = i. Wild Gambit plays one when a card is played (DESIGN 96).",
        "local _, ns = ...",
        "ns.DB = ns.DB or {}",
        "ns.DB.voices = { SETS = {",
    ]
    out += ["{%d,%d,%d}," % s for s in sets]
    out.append("}, DISPLAY = {")
    line = []
    for d, i in disp_idx.items():
        line.append("[%d]=%d," % (d, i))
        if len(line) == 20:
            out.append("".join(line)); line = []
    if line: out.append("".join(line)); line = []
    out.append("}, NPC = {")
    for n, i in npc_idx.items():
        line.append("[%d]=%d," % (n, i))
        if len(line) == 20:
            out.append("".join(line)); line = []
    if line: out.append("".join(line))
    out.append("} }")
    path = os.path.join(ROOT, "Data", "CreatureVoices.lua")
    open(path, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    words = sum(1 for v in by_npc.values() if v[0])
    cries = sum(1 for v in by_npc.values() if not v[0] and v[1])
    print("%s: %d sets, %d models, %d creatures (%d with words, %d with a battle cry)" % (
        os.path.basename(path), len(sets), len(disp_idx), len(npc_idx), words, cries))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])

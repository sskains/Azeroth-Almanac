"""
Azeroth Almanac - the names of the creatures that drop quest items (Data/QuestMobs.lua), from VMaNGOS.

(Shannon, 2026-10-12; DESIGN 105) The hidden item database (Data/Items.lua) knows which creatures drop
an item only by their IDs; the game names a creature once the player meets it. The Quest Targeter
needs a name to target, count and mark a creature, so a quest item whose droppers hadn't been met
had no target button. This file gives those names - only for creatures that drop an item some quest
asks for, and only for targeting: the Almanac's pages still show a creature only once it's met.

Usage: python build_quest_mobs.py <mangos.sqlite> <Data/Items.lua> <output QuestMobs.lua>

Output:
  ns.DB.questMob[creatureID] = "Name"
"""
import re
import sqlite3
import sys


def main(db_path, items_path, out_path):
    db = sqlite3.connect(db_path)
    # the items any quest asks for
    wanted = set()
    for row in db.execute("SELECT ReqItemId1, ReqItemId2, ReqItemId3, ReqItemId4 FROM quest_template"):
        for item in row:
            if item:
                wanted.add(int(item))
    # their droppers, as Data/Items.lua lists them ([item]={count,"npc:chance,..."})
    droppers = set()
    for line in open(items_path, encoding="utf-8"):
        m = re.match(r'^\[(\d+)\]=\{\d+,"([^"]*)"', line)
        if m and int(m.group(1)) in wanted:
            for part in m.group(2).split(","):
                if ":" in part:
                    droppers.add(int(part.split(":")[0]))
    # their names (the latest patch's row)
    names = {}
    for entry, patch, name in db.execute("SELECT entry, patch, name FROM creature_template ORDER BY entry, patch"):
        if entry in droppers and name:
            names[entry] = name
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("-- Generated by tools/build_quest_mobs.py from the VMaNGOS world database\n")
        f.write("-- (github.com/vmangos/core, GPL-2.0; see Licenses\\VMaNGOS.txt). The names of the creatures that\n")
        f.write("-- drop an item a quest asks for, for the Quest Targeter only (DESIGN 105). Do not edit by hand.\n")
        f.write("local _, ns = ...\nns.DB = ns.DB or {}\nns.DB.questMob = {\n")
        for entry in sorted(names):
            f.write('[%d]=%s,\n' % (entry, '"' + names[entry].replace("\\", "\\\\").replace('"', '\\"') + '"'))
        f.write("}\n")
    print("quest items %d, droppers %d, named %d" % (len(wanted), len(droppers), len(names)))


if __name__ == "__main__":
    if len(sys.argv) != 4:
        print(__doc__)
        sys.exit(1)
    main(*sys.argv[1:])
